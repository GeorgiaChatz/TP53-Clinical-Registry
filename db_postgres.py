"""PostgreSQL storage for local fictional-data development. No real patient data."""
import os, json
from datetime import datetime, timezone
import psycopg
from psycopg.rows import dict_row


def now():
    return datetime.now(timezone.utc).isoformat(timespec='seconds')


def conn():
    url = os.getenv('DATABASE_URL')
    if not url:
        raise RuntimeError('DATABASE_URL is not configured. See README.')
    return psycopg.connect(url, row_factory=dict_row)


def init():
    with conn() as c:
        with c.cursor() as cur:
            cur.execute('''CREATE TABLE IF NOT EXISTS patients (
                patient_id TEXT PRIMARY KEY, center TEXT NOT NULL DEFAULT '',
                diagnosis TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, updated_at TEXT NOT NULL
            )''')
            cur.execute('''CREATE TABLE IF NOT EXISTS section_entries (
                entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                patient_id TEXT NOT NULL REFERENCES patients(patient_id) ON DELETE CASCADE,
                section TEXT NOT NULL, episode INTEGER NOT NULL DEFAULT 1,
                data_json TEXT NOT NULL DEFAULT '{}', updated_at TEXT NOT NULL,
                UNIQUE(patient_id, section, episode)
            )''')
            cur.execute('''CREATE TABLE IF NOT EXISTS audit_events (
                audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                patient_id TEXT NOT NULL, section TEXT NOT NULL,
                episode INTEGER, action TEXT NOT NULL, old_json TEXT,
                new_json TEXT, recorded_at TEXT NOT NULL
            )''')


def fetch_all(sql, params=()):
    with conn() as c:
        return c.execute(sql, params).fetchall()


def fetch_one(sql, params=()):
    with conn() as c:
        return c.execute(sql, params).fetchone()


def list_patients(search=''):
    pat=f'%{search.strip()}%'
    return fetch_all('''SELECT * FROM patients WHERE patient_id ILIKE %s OR center ILIKE %s
      OR diagnosis ILIKE %s ORDER BY updated_at DESC''',(pat,pat,pat))


def get_patient(pid):
    return fetch_one('SELECT * FROM patients WHERE patient_id=%s',(pid,))


def create_patient(pid,center='',diagnosis=''):
    pid=pid.strip()
    if not pid or len(pid)>60: raise ValueError('Patient research ID must be 1–60 characters.')
    if not all(ch.isalnum() or ch in '-_.' for ch in pid):
        raise ValueError('Only letters, digits, hyphens, underscores and dots are allowed in the research ID.')
    stamp=now()
    with conn() as c:
        c.execute('INSERT INTO patients VALUES (%s,%s,%s,%s,%s)',(pid,center,diagnosis,stamp,stamp))
        c.execute('''INSERT INTO audit_events(patient_id,section,episode,action,new_json,recorded_at)
          VALUES (%s,%s,%s,%s,%s,%s)''',
          (pid,'Patient registry',None,'Created',json.dumps({'center':center,'diagnosis':diagnosis}),stamp))


def update_patient(pid,center=None,diagnosis=None):
    with conn() as c:
        p=c.execute('SELECT * FROM patients WHERE patient_id=%s FOR UPDATE',(pid,)).fetchone()
        if not p: raise ValueError('Patient not found')
        old={'center':p['center'],'diagnosis':p['diagnosis']}
        new={'center':old['center'] if center is None else center,
             'diagnosis':old['diagnosis'] if diagnosis is None else diagnosis}
        if new==old:return
        stamp=now()
        c.execute('UPDATE patients SET center=%s,diagnosis=%s,updated_at=%s WHERE patient_id=%s',
                  (new['center'],new['diagnosis'],stamp,pid))
        c.execute('''INSERT INTO audit_events(patient_id,section,action,old_json,new_json,recorded_at)
          VALUES (%s,%s,%s,%s,%s,%s)''',
          (pid,'Patient registry','Updated',json.dumps(old),json.dumps(new),stamp))


def entries(pid,section=None):
    if section:
        rows=fetch_all('''SELECT * FROM section_entries WHERE patient_id=%s AND section=%s
          ORDER BY episode''',(pid,section))
    else:
        rows=fetch_all('''SELECT * FROM section_entries WHERE patient_id=%s
          ORDER BY section,episode''',(pid,))
    return [{**r,'data':json.loads(r['data_json'])} for r in rows]


def get_entry(pid,section,episode=1):
    r=fetch_one('''SELECT data_json FROM section_entries WHERE patient_id=%s
      AND section=%s AND episode=%s''',(pid,section,episode))
    return json.loads(r['data_json']) if r else {}


def next_episode(pid,section):
    r=fetch_one('SELECT MAX(episode) AS max_episode FROM section_entries WHERE patient_id=%s AND section=%s',(pid,section))
    return (r['max_episode'] or 0)+1


def save_entry(pid,section,episode,data):
    clean={k:v for k,v in data.items() if v is not None and str(v).strip()}
    stamp=now()
    with conn() as c:
        p=c.execute('SELECT patient_id FROM patients WHERE patient_id=%s FOR UPDATE',(pid,)).fetchone()
        if not p: raise ValueError('Patient not found')
        r=c.execute('''SELECT data_json FROM section_entries WHERE patient_id=%s
          AND section=%s AND episode=%s FOR UPDATE''',(pid,section,episode)).fetchone()
        old=json.loads(r['data_json']) if r else {}
        if clean==old:return False
        c.execute('''INSERT INTO section_entries(patient_id,section,episode,data_json,updated_at)
          VALUES (%s,%s,%s,%s,%s) ON CONFLICT(patient_id,section,episode)
          DO UPDATE SET data_json=excluded.data_json, updated_at=excluded.updated_at''',
          (pid,section,episode,json.dumps(clean,ensure_ascii=False),stamp))
        c.execute('UPDATE patients SET updated_at=%s WHERE patient_id=%s',(stamp,pid))
        c.execute('''INSERT INTO audit_events(patient_id,section,episode,action,old_json,new_json,recorded_at)
          VALUES (%s,%s,%s,%s,%s,%s,%s)''',
          (pid,section,episode,'Updated' if old else 'Saved',json.dumps(old,ensure_ascii=False),
           json.dumps(clean,ensure_ascii=False),stamp))
    return True


def audit(pid):
    return fetch_all('SELECT * FROM audit_events WHERE patient_id=%s ORDER BY audit_id DESC',(pid,))


def stats():
    p=fetch_one('SELECT COUNT(*) AS n FROM patients')
    e=fetch_one('SELECT COUNT(*) AS n FROM section_entries')
    return p['n'],e['n']


